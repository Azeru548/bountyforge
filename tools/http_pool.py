#!/usr/bin/env python3
"""
BountyForge HTTP pool - shared async client + response classification heuristics.

Upstream ships five engines that import this module (auth_manager,
race_engine, smuggle_engine, ssrf_engine, waf_detector) but the file itself
was never committed, so every one of them exits at startup with
"[!] http_pool.py required".  This implements the API those call sites use:

    pool = HTTPPool(max_connections=30, timeout=15)
    await pool.start()
    result = await pool.request("GET", url, headers={...},
                                json_data=..., data=..., allow_redirects=True)
    await pool.stop()

    pool.random_ua()
    pool.is_waf_block(result)
    pool.is_internal_response(result, baseline)
    pool.is_metadata_response(result)
    await pool.detect_http_version(url)      # {"h1": bool, "h2": bool}

Status codes on failure (both are probed by auth_manager):
    -1  connection / TLS / protocol error
    -3  timeout

Set BF_SSL_VERIFY=0 to accept self-signed and mismatched certificates,
which staging and internal targets commonly present.
"""

